import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { installToDevVault } from './scripts/install-dev.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

// Modes: "production" (minified, dev helpers removed), "dev-once" (one dev build
// copied into ./dev-vault), or no argument (watch mode, copied after every build).
const mode = process.argv[2] ?? 'watch';
const prod = mode === 'production';

/**
 * In watch mode, copy every successful build into the disposable ./dev-vault.
 * The target path is fixed inside this repository (see scripts/install-dev.mjs),
 * so a development build can never be written into a real vault.
 */
const devVaultPlugin = {
	name: 'install-dev-vault',
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length === 0) installToDevVault();
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2022',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	define: {
		// Development-only helpers (e.g. the sample analysis button) are dropped from production builds.
		__DEV__: prod ? 'false' : 'true',
	},
	plugins: prod ? [] : [devVaultPlugin],
});

if (mode === 'watch') {
	await context.watch();
} else {
	await context.rebuild();
	await context.dispose();
	process.exit(0);
}
